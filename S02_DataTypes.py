
'''
Datatypes In python

┌────────────┬──────────────────┬──────────────────────┐
│ Data Type  │ Definition       │ Example              │
├────────────┼──────────────────┼──────────────────────┤
│ int        │ Whole numbers    │ age = 20             │
│ float      │ Decimal numbers  │ price = 10.5         │
│ complex    │ Complex numbers  │ z = 2 + 3j           │
│ str        │ Text             │ name = "Rahul"       │
│ bool       │ True or False    │ x = True             │
│ NoneType   │ No value         │ x = None             │
└────────────┴──────────────────┴──────────────────────┘
'''



'''

------------------------------------------------------------
1. int (Integer)
------------------------------------------------------------
Definition:
int is used to store whole numbers without decimal values.

Example:
'''
age = 20
print("1. int Example:")
print("Age =", age)
print("Type =", type(age))
print()

'''

------------------------------------------------------------
2. float (Floating Point)
------------------------------------------------------------
Definition:
float is used to store numbers containing decimal values.
Example:
'''
price = 10.5
print("2. float Example:")
print("Price =", price)
print("Type =", type(price))
print()

'''

------------------------------------------------------------
3. complex (Complex Number)
------------------------------------------------------------
Definition:
complex is used to store complex numbers.
A complex number contains a real part and an imaginary part.

Example:
'''

z = 2 + 3j

print("3. complex Example:")
print("Complex Number =", z)
print("Type =", type(z))
print()

'''

------------------------------------------------------------
4. str (String)
------------------------------------------------------------
Definition:
str is used to store text or a sequence of characters.
Strings are written inside single or double quotes.

Example:
'''

name = "Rahul"

print("4. str Example:")
print("Name =", name)
print("Type =", type(name))
print()

'''
------------------------------------------------------------
5. bool (Boolean)
------------------------------------------------------------
Definition:
bool is used to represent one of two values:
True or False.

Example:
'''

is_student = True

print("5. bool Example:")
print("Is Student =", is_student)
print("Type =", type(is_student))
print()

''' 

------------------------------------------------------------
6. NoneType (None)
------------------------------------------------------------
Definition:
None is used to represent the absence of a value
or "no value".

Example:
'''

result = None

print("6. NoneType Example:")
print("Result =", result)
print("Type =", type(result))
print()


                             

